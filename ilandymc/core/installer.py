import asyncio, json, os, re, shutil, tempfile, secrets, socket, ctypes, subprocess, time
from pathlib import Path
from .java_manager import inspect_java, required_java_major
from .server_manager import ServerManager
from ..providers.registry import provider_for
from ..utils.downloads import download_verified

class InstallError(RuntimeError): pass

def _rename_noreplace(source: Path, destination: Path):
    # Linux renameat2(RENAME_NOREPLACE): atomic commit that cannot clobber an empty
    # destination directory created concurrently by another process.
    libc = ctypes.CDLL(None, use_errno=True)
    fn = getattr(libc, "renameat2", None)
    if fn is None:
        raise InstallError("This Linux system lacks atomic no-replace rename support")
    fn.argtypes = [ctypes.c_int, ctypes.c_char_p, ctypes.c_int, ctypes.c_char_p, ctypes.c_uint]
    fn.restype = ctypes.c_int
    result = fn(-100, os.fsencode(source), -100, os.fsencode(destination), 1)
    if result != 0:
        err = ctypes.get_errno()
        if err == 17: raise FileExistsError(destination)
        raise OSError(err, os.strerror(err), str(destination))

def _valid_name(name):
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{0,31}", name):
        raise ValueError("Server name must be 1-32 letters, digits, '_' or '-' and start alphanumeric")


def _assert_game_port_available(port: int):
    # Minecraft Java Edition uses TCP for the gameplay listener. This is a preflight
    # check only; another process can still claim the port before the server starts.
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
            probe.bind(("0.0.0.0", port))
    except OSError as exc:
        raise InstallError(f"Minecraft TCP port {port} is unavailable") from exc


def _bootstrap_properties(staging: Path, java: str, memory_mb: int, timeout: int = 180) -> dict[str, str]:
    """Run the downloaded server once in an isolated staging directory.

    The server itself writes its version-specific server.properties. We deliberately
    do not seed it with the catalogue: unsupported keys must never leak into older
    server releases. A loopback-only server-ip and ephemeral port 0 prevent a public fixed-port listener during bootstrap.
    """
    from .properties import parse_properties
    # server-ip has existed across the supported Java server generations; keep
    # bootstrap loopback-only. All other options are generated by the server itself.
    (staging / "server.properties").write_text("server-ip=127.0.0.1\n", encoding="utf-8")
    log_path = staging / ".bootstrap.log"
    with log_path.open("wb") as log:
        proc = subprocess.Popen(
            [java, f"-Xms{min(memory_mb, 1024)}M", f"-Xmx{memory_mb}M", "-jar", str(staging / "server.jar"), "--port", "0", "nogui"],
            cwd=staging, stdin=subprocess.PIPE, stdout=log, stderr=subprocess.STDOUT,
            start_new_session=True, close_fds=True,
            env={**os.environ, "LANG": "C.UTF-8"})
        deadline = time.monotonic() + timeout
        ready = False
        try:
            while time.monotonic() < deadline:
                if proc.poll() is not None:
                    break
                try:
                    output = log_path.read_text(encoding="utf-8", errors="replace")
                except OSError:
                    output = ""
                if "Done (" in output or "For help, type" in output:
                    ready = True
                    break
                time.sleep(0.25)
            if not ready:
                raise InstallError(
                    f"Server bootstrap did not reach ready state within {timeout}s; "
                    f"inspect {log_path.name}. Installation was not committed.")
            try:
                proc.stdin.write(b"stop\n")
                proc.stdin.flush()
                proc.stdin.close()
            except (BrokenPipeError, OSError):
                pass
            try:
                proc.wait(timeout=60)
            except subprocess.TimeoutExpired:
                proc.terminate()
                try: proc.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    proc.kill(); proc.wait(timeout=5)
                raise InstallError("Server did not stop after bootstrap; installation aborted")
        except Exception:
            if proc.poll() is None:
                proc.terminate()
                try: proc.wait(timeout=10)
                except subprocess.TimeoutExpired: proc.kill(); proc.wait(timeout=5)
            raise
    prop = staging / "server.properties"
    if not prop.is_file():
        raise InstallError("Server did not generate server.properties during bootstrap")
    values, _ = parse_properties(prop.read_text(encoding="utf-8", errors="replace"))
    if not values:
        raise InstallError("Generated server.properties is empty; installation aborted")
    log_path.unlink(missing_ok=True)
    return values


def install_server(name, software, version, memory_mb, root=Path("/opt/ilandy/servers"),
                   java="java", dry_run=False, accept_eula=False, game_port=25565):
    _valid_name(name)
    if not 512 <= memory_mb <= 1_000_000:
        raise ValueError("Memory allocation outside safe bounds")
    if not isinstance(game_port, int) or isinstance(game_port, bool) or not 1024 <= game_port <= 65535:
        raise ValueError("Game port must be between 1024 and 65535")
    if not accept_eula and not dry_run:
        raise InstallError("You must explicitly accept the Minecraft EULA (pass --accept-eula)")
    _assert_game_port_available(game_port)
    required = required_java_major(version)
    runtime = inspect_java(java)
    if runtime is None or runtime.major < required:
        raise InstallError(f"Java {required}+ required; selected runtime is missing or incompatible")
    manager = ServerManager(root); path = manager.server_path(name)
    if path.exists(): raise FileExistsError(f"Refusing to overwrite {path}")
    if dry_run: return path
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o750)
    staging = Path(tempfile.mkdtemp(prefix=f".{name}.install-", dir=path.parent))
    try:
        async def fetch():
            provider = provider_for(software)
            try:
                artifact = await provider.latest_artifact(version)
                if artifact.software != software or artifact.minecraft_version != version:
                    raise InstallError("Provider returned mismatched artifact metadata")
                await download_verified(artifact.download_url, staging / "server.jar",
                    checksum=artifact.checksum,
                    checksum_algorithm=artifact.checksum_algorithm or "sha256")
                return artifact
            finally:
                await provider.close()
        artifact = asyncio.run(fetch())
        (staging / "eula.txt").write_text("# Accepted by administrator\neula=true\n", encoding="utf-8")
        # RCON is bound to loopback and protected by a per-server random secret.
        with socket.socket() as probe:
            probe.bind(("127.0.0.1", 0))
            rcon_port = probe.getsockname()[1]
        rcon_password = secrets.token_urlsafe(32)
        (staging / "rcon.secret").write_text(rcon_password + "\n", encoding="utf-8")
        os.chmod(staging / "rcon.secret", 0o600)
        from .properties import SPECS
        # Let this exact server build emit its own canonical property set first.
        generated = _bootstrap_properties(staging, runtime.executable, memory_mb)
        supported_keys = sorted(set(generated).intersection(spec.key for spec in SPECS))
        property_values = dict(generated)
        managed_values = {
            "server-port": str(game_port), "online-mode": "false",
            "management-server-enabled": "false",
            "management-server-host": "127.0.0.1",
        }
        for key, value in managed_values.items():
            if key in generated:
                property_values[key] = value
        rcon_keys = {"enable-rcon", "rcon.port", "rcon.password", "rcon.ip"}
        if rcon_keys.issubset(generated):
            property_values.update({
                "enable-rcon": "true", "rcon.port": str(rcon_port),
                "rcon.password": rcon_password, "rcon.ip": "127.0.0.1"})
        elif "enable-rcon" in generated:
            property_values["enable-rcon"] = "false"
        # Keep every native/unknown line the server generated; add no speculative keys.
        from .properties import serialize_detected_properties
        (staging / "server.properties").write_text(
            serialize_detected_properties(property_values, supported_keys), encoding="utf-8")
        metadata = {"schema_version": 1, "name": name, "software": software,
            "minecraft_version": version, "build": artifact.build, "jar": "server.jar",
            "java": runtime.executable, "java_major": runtime.major, "memory_mb": memory_mb,
            "created_at": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat(),
            "eula_accepted": True, "rcon_port": rcon_port, "game_port": game_port,
            "properties_detected": True, "supported_properties": supported_keys}
        meta_tmp = staging / ".ilandy.json.tmp"
        meta_tmp.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
        os.chmod(meta_tmp, 0o640); os.replace(meta_tmp, staging / "ilandy.json")
        os.chmod(staging / "server.jar", 0o640)
        os.chmod(staging, 0o750)
        # Atomic commit on the same filesystem. Never replace an existing server.
        _rename_noreplace(staging, path)
        return path
    except Exception:
        shutil.rmtree(staging, ignore_errors=True)
        raise

